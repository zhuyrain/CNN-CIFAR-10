.section .text.init, "ax"
    .global _start

/* ================================================== */
/* 1. 中断向量表 (Vector Table)*/
/* 严格掌控 0x00 到 0x10 的绝对物理空间*/
/* ================================================== */

/* 绝对地址 0x00000000：复位入口 */
_start:
    j real_start        /* 直接跳到后面去，把空间让出来！占 4 字节 */

/* 绝对地址 0x00000010：异常入口 */
.org 0x10
trap_loop:
    j trap_loop         /* 发生异常跳进这里死循环 */

/* ================================================== */
/* 2. 真正的启动代码 (可以无限长) */
/* 紧跟在 0x10 的代码之后（通常从 0x14 开始）*/
/* ================================================== */
real_start:
    /* 初始化栈指针 */
    la sp, _sp

    /* 清零 BSS 段 */
    la t0, _bss_start
    la t1, _bss_end
    bgeu t0, t1, 2f
1:
    sw zero, 0(t0)
    addi t0, t0, 4
    bltu t0, t1, 1b
2:

    /* 进入 C 语言世界 */
    jal ra, main
    
end_loop:
    j end_loop